const testProfileByCode = new Map(
    limsLabWorkflowData.testCatalog.map((test) => [test.testCode.toUpperCase(), test])
);

const testProfileById = new Map(
    limsLabWorkflowData.testCatalog.map((test) => [test.id, test])
);

export const getOrderableLabTests = () =>
    limsLabWorkflowData.testCatalog
        .filter((test) => test.orderable)
        .map(({ id, testCode, testName, category, price, sampleType, tubeType, turnAroundTimeHours, department, requiresFasting }) => ({
            id,
            testCode,
            testName,
            category,
            price,
            sampleType,
            tubeType,
            turnAroundTimeHours,
            department,
            requiresFasting,
            source: 'static-catalog',
        }));

export const findLabTestWorkflowProfile = (test) => {
    if (!test) return null;
    const code = typeof test === 'string' ? test : test.testCode;
    const id = typeof test === 'string' ? test : test.id;
    return (code ? testProfileByCode.get(code.toUpperCase()) : null) ?? (id ? testProfileById.get(id) : null) ?? null;
};

export const enrichLabTestWithWorkflowData = (test) => {
    const profile = findLabTestWorkflowProfile(test);
    if (!profile) {
        return test;
    }

    return {
        ...test,
        category: test.category ?? profile.category,
        price: Number(test.price ?? profile.price),
        sampleType: test.sampleType ?? profile.sampleType,
        tubeType: test.tubeType ?? profile.tubeType,
        turnAroundTimeHours: test.turnAroundTimeHours ?? profile.turnAroundTimeHours,
        department: test.department ?? profile.department,
        requiresFasting: test.requiresFasting ?? profile.requiresFasting,
        parametersCount: profile.parameters.length,
        analyzer: profile.analyzer,
        specimenVolume: profile.specimenVolume,
    };
};

